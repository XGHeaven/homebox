const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const ts=require('typescript')
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'homebox-results-'))
const file=path.join(dir,'results.cjs')
fs.writeFileSync(file,ts.transpileModule(fs.readFileSync(path.join(__dirname,'../src/llm/results.ts'),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText)
const {snapshotConfig,sanitizeResult,readResults,saveResult,removeResult,legacyResultsKey}=require(file)
fs.rmSync(dir,{recursive:true})
function storage(){const data=new Map();return {get length(){return data.size},key:i=>[...data.keys()][i]??null,getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)}}
const record=id=>({id,config:{endpoint:'https://example.com/v1?api_key=SECRET&region=foo',key:'SECRET'},elapsedMs:1,results:[{id:0,status:'success',outputPreview:'PRIVATE'}],speedSamples:[],tpsSamples:[]})
test('result snapshots remove credentials and queries without changing request configuration',()=>{
 const original=record('a')
 const safe=sanitizeResult(original)
 assert.equal(safe.config.endpoint,'https://example.com/v1')
 assert.ok(!JSON.stringify(safe).includes('SECRET'))
 assert.ok(!JSON.stringify(safe).includes('PRIVATE'))
 assert.ok(original.config.endpoint.includes('SECRET'))
 assert.equal(snapshotConfig({endpoint:'https://user:pass@example.com/v1?token=x#frag'}).endpoint,'https://example.com/v1')
})
test('independent record writes preserve other tabs saves and deletions',()=>{
 const store=storage()
 store.setItem(legacyResultsKey,JSON.stringify([record('a')]))
 const tabA=readResults(store),tabB=readResults(store)
 assert.equal(tabA.length,tabB.length)
 saveResult(store,record('b'))
 saveResult(store,record('c'))
 removeResult(store,tabB[0].id)
 assert.deepEqual(readResults(store).map(r=>r.id),['c','b'])
 saveResult(store,record('d'))
 removeResult(store,'c')
 assert.deepEqual(readResults(store).map(r=>r.id),['d','b'])
 // Reload does not resurrect a legacy row, and a deliberate save can restore it.
 assert.deepEqual(readResults(store).map(r=>r.id),['d','b'])
 saveResult(store,record('a'))
 assert.deepEqual(readResults(store).map(r=>r.id),['d','b','a'])
 assert.ok(!JSON.stringify(readResults(store)).includes('SECRET'))
})
